#!/usr/bin/env python3
"""Reproduce the checked-in native motion core from the pinned decompilation.

Android builds use the generated C++ files, never Python or PowerPC objects.
The generated code keeps the original interpolation, IK and joint blending;
disk offsets, unaligned reads and native pointers have distinct representations.
"""
from pathlib import Path
import importlib.util
import re
import tempfile

root = Path(__file__).resolve().parent.parent
up = root / 'upstream/re4'
out = root / 'app/src/main/cpp/ports/motion64'
out.mkdir(parents=True, exist_ok=True)
spec = importlib.util.spec_from_file_location('motion_prepare', up / 'tools/motion/host/prepare.py')
prep = importlib.util.module_from_spec(spec)
spec.loader.exec_module(prep)

def replace(text, old, new):
    assert text.count(old) == 1, old
    return text.replace(old, new)

banner = ('// Derived from upstream/re4 at 9b76ff003081d6ece8b838453fb8310743a972c7.\n'
          '// Generated by tools/generate_motion64.py; see docs/PLAYER-PREVIEW.md.\n')
header = (up / 'tools/motion/host/stub/re4_host_stub.h').read_text()
header = header[header.index('typedef int8_t'):header.rindex('#endif')]
header = re.sub(r'// The game\'s libm.*?#define acosf re4_acosf\n',
                '// Original newlib 1.8.2 fdlibm, scoped to the motion core.\n'
                '// A single trig ULP can change the two-bone IK reach branch.\n'
                'using re4::fdlibm::sinf;\nusing re4::fdlibm::cosf;\n'
                'using re4::fdlibm::acosf;\n', header, flags=re.S)
header = replace(header, '    u8 nParts;\n};',
                 '    u8 nParts;\n    u16* kinds;\n    u8* parts;\n    u8** curves;\n};')
header = header.replace('u32* pHermite_data;   // u32 key pointers: the motion image lives in the low 4 GB (MAP_32BIT)',
                        'u8** pHermite_data;  // Validated, owned native pointers; no file relocation.')
header = replace(header, 'extern "C" {\n', '')
header = replace(header, 'void eprintf(int x, int y, int a, int b, const char* fmt, ...);\n}',
                 'void eprintf(int x, int y, int a, int b, const char* fmt, ...);')
helpers = '''inline u16 Native16(const void* p) {
    const u8* b = static_cast<const u8*>(p);
    return u16(b[0]) | (u16(b[1]) << 8);
}
inline u32 Native32(const void* p) {
    const u8* b = static_cast<const u8*>(p);
    return u32(b[0]) | (u32(b[1]) << 8) | (u32(b[2]) << 16) | (u32(b[3]) << 24);
}
'''
(out / 'runtime.h').write_text(banner + '#pragma once\n#include <cstdint>\n#include <cstddef>\n#include <cmath>\n#include "../fdlibm/fdlibm.h"\nnamespace re4::motion64 {\n' + header + helpers + '}\n')

def portable(s):
    s = prep.host_text(s)
    s = re.sub(r'^#include .*\n', '', s, flags=re.M)
    s = re.sub(r'^#line .*\n', '', s, flags=re.M)
    s = re.sub(r'\bregister\s+', '', s)
    # A tied register output is a real identity assignment (MotionHokan's pm).
    # Other empty statements only constrain the original PowerPC scheduler.
    # In particular =m(vx) must not tell Clang that initialized memory changed.
    s = re.sub(r'asm\(""\s*:\s*"=r"\((\w+)\)\s*:\s*"0"\(([^)]+)\)\);',
               r'\1 = \2;', s)
    s = re.sub(r'\s*asm(?: volatile)?\(""\s*:[^;]*;', '', s)
    return s

motion = portable((up / 'src/game/motion.cpp').read_text())
motion = replace(motion, '    u32* tbl;\n', '')
motion = replace(motion, '    w->pJoint_kind = (u16*) ((u8*) w->pMot + 3);\n    w->pJoint_no = (u8*) w->pMot + (w->Joint_num * 2 + 3);',
                 '    w->pJoint_kind = data->kinds;\n    w->pJoint_no = data->parts;')
start = motion.index('    // Two statements: the end pointer lives in `tbl`')
stop = motion.index('    w->Null_rot', start)
motion = motion[:start] + '    w->pHermite_data = data->curves;\n' + motion[stop:]
motion = replace(motion, 'int n = *(s32*) pEm->pDblJnt;', 'int n = static_cast<int>(Native32(pEm->pDblJnt));')
motion = replace(motion, 'u16* hp = hist - 1;', 'u16* hp = hist;')
motion = replace(motion, '        hp++;\n', '')
motion = replace(motion, '        o[axis] = r;', '        o[axis] = r;\n        hp++;')
motion = replace(motion, '        n = *(u16*) p;', '        n = Native16(p);')
motion = replace(motion, '                f0 = (f32) *fp;', '                f0 = (f32) Native16(fp);')
motion = replace(motion, '                    f1 = (f32) frames[nx];', '                    f1 = (f32) Native16(reinterpret_cast<u8*>(frames) + nx * 2);')
motion = replace(motion, '    f32 val[2];\n    f32 tan[2];', '    f32 val[2]{};\n    f32 tan[2]{};')
# Address arithmetic on byte streams must not form misaligned u16 pointers.
motion = motion.replace('u16* frames;', 'u8* frames;').replace('u16* fp = (u16*) (idx * 2 + (uintptr_t) frames);', 'u8* fp = frames + idx * 2;')
motion = motion.replace('frames = (u16*) (p + 2);', 'frames = p + 2;')
motion = motion.replace('fp = (u16*) (last * 2 + (uintptr_t) frames);', 'fp = frames + last * 2;')
motion = motion.replace('                    fp--;', '                    fp -= 2;').replace('                    fp++;', '                    fp += 2;')
(out / 'motion.cpp').write_text(banner + '#include "runtime.h"\n#include <cstring>\nnamespace re4::motion64 {\n' + motion + '\n}\n')
ik = portable((up / 'src/game/ik.cpp').read_text())
(out / 'ik.cpp').write_text(banner + '#include "runtime.h"\nnamespace re4::motion64 {\n' + ik + '\n}\n')

extracts = [
    ('src/game/math_sub.cpp', 'hermite RotMatrix TransMatrix ScaleMatrix VecRadLimit SetOrientationZX SetOrientationZY VecAngle VecLinearCombination'),
    ('src/game/sub2.cpp', 'RootSumSquare3 GetDistance3'),
    ('src/game/model.cpp', 'cModel::partsMatCalc cModel::partsWorldCalc cModel::getPartsPtr cModel::matBlend'),
    ('src/lib/mtx.c', 'C_MTXIdentity C_MTXCopy C_MTXConcat C_MTXInverse C_MTXTranspose C_MTXTrans C_MTXScale C_MTXRotTrig C_MTXRotRad C_MTXRotAxisRad C_MTXQuat'),
    ('src/lib/mtxvec.c', 'C_MTXMultVec C_MTXMultVecSR'),
    ('src/lib/vec.c', 'C_VECAdd C_VECSubtract C_VECScale C_VECNormalize C_VECSquareMag C_VECMag C_VECDotProduct C_VECCrossProduct'),
    ('src/lib/quat.c', 'C_QUATMtx C_QUATSlerp'),
]
chunks = []
with tempfile.TemporaryDirectory() as tmp:
    p = Path(tmp) / 'extract.cpp'
    for source, names in extracts:
        prep.extract(str(up / source), str(p), names.split())
        chunks.append('// ' + source + '\n' + portable(p.read_text()))
(out / 'math.cpp').write_text(banner + '#include "runtime.h"\nnamespace re4::motion64 {\n' + '\n'.join(chunks) + '\n}\n')

# Keep the game's libm inside its own namespace. Public C names or macros
# would silently replace math for unrelated parsers, camera and GL code.
# This is the dependency closure for the original float sin/cos/acos.
fdout = out.parent / 'fdlibm'
fdout.mkdir(parents=True, exist_ok=True)
(fdout / 'fdlibm.h').write_text(banner + '''#pragma once
namespace re4::fdlibm {
float sinf(float x);
float cosf(float x);
float acosf(float x);
}
''')
(fdout / 'fdlibm_internal.h').write_text(banner + '''#pragma once
#include "fdlibm.h"
#include <cstdint>
#include <cstring>
#include <cmath>
namespace re4::fdlibm {
using __int32_t = std::int32_t;
using __uint32_t = std::uint32_t;
float fabsf(float x);
float floorf(float x);
float scalbnf(float x, int n);
float sqrtf(float x);
__int32_t __ieee754_rem_pio2f(float x, float *y);
float __kernel_sinf(float x, float y, int tail);
float __kernel_cosf(float x, float y);
int __kernel_rem_pio2f(float *x, float *y, int exponent, int count, int precision,
                     const __int32_t *twoOverPi);
// The original union macros inspect IEEE float words. memcpy preserves the
// bits on Android ARM64 and the host without aliasing or endian assumptions.
inline std::uint32_t floatWord(float value) {
    std::uint32_t bits;
    std::memcpy(&bits, &value, sizeof(bits));
    return bits;
}
inline float floatFromWord(std::uint32_t bits) {
    float value;
    std::memcpy(&value, &bits, sizeof(value));
    return value;
}
}
// Private to these implementation files; never included by runtime.h.
#define GET_FLOAT_WORD(word, value) \\
    do { (word) = re4::fdlibm::floatWord(value); } while (0)
#define SET_FLOAT_WORD(value, word) \\
    do { (value) = re4::fdlibm::floatFromWord(word); } while (0)
''')
fd_sources = ('sf_sin sf_cos kf_sin kf_cos ef_rem_pio2 kf_rem_pio2 '
              'sf_scalbn sf_floor sf_fabs ef_acos ef_sqrt').split()
for name in fd_sources:
    source = (up / 'src/lib/fdlibm' / (name + '.c')).read_text()
    source = replace(source, '#include "fdlibm.h"', '')
    source = source.replace('__ieee754_acosf', 'acosf')
    source = source.replace('__ieee754_sqrtf', 'sqrtf')
    if name == 'ef_sqrt':
        # The original packs a possibly negative exponent into unsigned IEEE
        # bits. Avoid a negative signed left shift with the same bit result.
        source = replace(source, '(m <<23)', '(static_cast<__uint32_t>(m) << 23)')
    (fdout / (name + '.cpp')).write_text(
        banner + '#include "fdlibm_internal.h"\nnamespace re4::fdlibm {\n' +
        source + '\n}\n')
print('Native motion/IK/math and original fdlibm sources regenerated.')
