#!/usr/bin/env python3
"""Create copyright-free, synthetic M21 knife/kick DRS test fixtures.

Usage: make_melee_fixtures.py OUTPUT_DIRECTORY

The archive indices follow the production loader's source mapping. All meshes,
colours, skeletons and curves are generated here or by make_grab_fixtures; none
are original game data. These fixtures exercise parsers, parent transforms,
melee state and GPU lifecycle. They cannot validate original poses, hit reach,
clip durations, authored travel or combat balance. No game file is read.
"""
from contextlib import redirect_stdout
from pathlib import Path
import argparse
import hashlib
import io
import json
import math
import struct
import tempfile

import make_grab_fixtures as grab


def generated_entries(data):
    """Read only the sparse envelopes just generated by our M20 helper."""
    body_offset = struct.unpack_from('>I', data, 0x2c)[0]
    body_size = struct.unpack_from('>I', data, 0x24)[0]
    body = data[body_offset:body_offset + body_size]
    count = struct.unpack_from('>I', body)[0]
    offsets = struct.unpack_from(f'>{count}I', body, 16)
    result = {}
    for index, offset in enumerate(offsets):
        tag_offset = 16 + count * 4 + index * 4
        tag = body[tag_offset:tag_offset + 4].rstrip(b'\0')
        if tag:
            end = offsets[index + 1] if index + 1 < count else len(body)
            result[index] = (tag.decode('ascii'), body[offset:end])
    return result


def hierarchy(joints):
    """An invented pelvis/torso/hand tree; never an original rest pose.

    Parts 1 and 2 accumulate the waist's two half turns. Part 3 is their
    counterrotating descendant; forearm9/hand10 inherit the torso, not that
    branch. The simplified 2 -> 9 -> 10 branch distinguishes the hit source
    (part9) from the visible knife's weight (part10).
    Ordered parents keep the production world-matrix walk well defined.
    """
    tree = [(255, (0., 0., 0.))]
    for part in range(1, joints):
        tree.append((0, ((part % 4) * 50., 500. + part * 15.,
                         (part % 3) * 30.)))
    replacements = {
        1: (0, (0., 700., 0.)),
        2: (1, (0., 400., 0.)),
        3: (2, (0., 0., 0.)),
        4: (2, (0., 400., 0.)),
        9: (2, (-300., 100., 200.)),
        10: (9, (-100., 0., 0.)),
        17: (3, (-100., -300., 0.)),
        18: (17, (0., -200., 0.)),
        22: (3, (100., -300., 0.)),
        23: (22, (0., -200., 0.)),
    }
    for part, record in replacements.items():
        if part < joints:
            tree[part] = record
    return tree


def model(joints, image=0, weight=0, blade=False):
    data = bytearray(grab.model(joints, image))
    tree = hierarchy(joints)
    for part, (parent, center) in enumerate(tree):
        offset = 64 + part * 16
        data[offset + 1] = parent
        struct.pack_into('>3f', data, offset + 4, *center)
    weights = struct.unpack_from('>I', data, 20)[0]
    data[weights] = weight
    if blade:
        # A generated narrow triangle along hand10's local -X. BIN vertices
        # live in bind/model coordinates; skinning subtracts the bind center.
        center = [0., 0., 0.]
        part = weight
        while part != 255:
            parent, local = tree[part]
            center = [a + b for a, b in zip(center, local)]
            part = parent
        vertices = struct.unpack_from('>I', data, 48)[0]
        points = [(0, -40, 0), (0, 40, 0), (-750, 0, 0)]
        for index, point in enumerate(points):
            positioned = [int(a + b) for a, b in zip(center, point)]
            struct.pack_into('>3hH', data, vertices + index * 8,
                             *positioned, 0)
    return bytes(data)


def hermite_motion(frames, channels):
    """Two-key format-0 Hermite channels with explicit linear tangents.

    Tangents are deltas over the complete normalized segment, not units/tick.
    Unlike type15, this layout initializes every value HermiteInterpolation
    consumes at intermediate frames in the unchanged original runtime.
    """
    table = (3 + len(channels) * 3 + 3) & ~3
    size = table + 4 + len(channels) * 4
    offsets = []
    for _ in channels:
        offsets.append(size)
        size += 90  # Three axes: count, two frames, two value/in/out triples.
    data = bytearray(size)
    grab.half(data, 0, frames)
    data[2] = len(channels)
    grab.word(data, table, size)
    for index, (kind, part, start, end) in enumerate(channels):
        grab.half(data, 3 + index * 2, kind)
        data[3 + len(channels) * 2 + index] = part
        grab.word(data, table + 4 + index * 4, offsets[index])
        offset = offsets[index]
        for axis in range(3):
            delta = end[axis] - start[axis]
            struct.pack_into('>3H6f', data, offset, 2, 0, frames,
                             start[axis], delta, delta, end[axis], delta, delta)
            offset += 30
    return bytes(data)


def upgrade_generated_motion(data):
    """Give inherited M20 direct-float test channels defined tangents.

    This reads only our generated two-key data. Source Fcc_get_data_033 writes
    no tangents; using its type15 with intermediate skeletal frames can read
    uninitialized tangents. Preserve the intended endpoint values in type0.
    The already valid M20 format-0 walk channel passes through unchanged.
    """
    frames = struct.unpack_from('>H', data)[0]
    count = data[2]
    kinds = struct.unpack_from(f'>{count}H', data, 3)
    if all(kind >> 12 == 0 for kind in kinds):
        return data
    if not all(kind >> 12 == 15 for kind in kinds):
        raise ValueError('Unexpected generated M20 motion format')
    table = (3 + count * 3 + 3) & ~3
    channels = []
    for index, kind in enumerate(kinds):
        part = data[3 + count * 2 + index]
        offset = struct.unpack_from('>I', data, table + 4 + index * 4)[0]
        start, end = [], []
        for _ in range(3):
            keys, first, last = struct.unpack_from('>3H', data, offset)
            if (keys, first, last) != (2, 0, frames):
                raise ValueError('Unexpected generated M20 key sequence')
            a, b = struct.unpack_from('>2f', data, offset + 6)
            start.append(a)
            end.append(b)
            offset += 14
        channels.append((kind & 0xfff, part, start, end))
    return hermite_motion(frames, channels)


def motion(frames=50, signature=0, hand=False, pitch=0., slash=False):
    """Invented finite Hermite curves with ordinary rotation channels.

    Root translation is zero. Torso motion also reaches hand9 via its parent.
    Knife hand -X faces synthetic local +Z at zero pitch, with a small authored
    test swing; this direction and reach are not an original-asset oracle.
    """
    channels = [(1, 0, (0., 0., 0.), (0., 0., 0.)),
                (2, 2, (-pitch, signature * .0001, 0.),
                 (-pitch, signature * .0001 + .04, .025))]
    if hand:
        swing = .2 if slash else .025
        channels.append((2, 9, (0., math.pi / 2 - swing, 0.),
                         (0., math.pi / 2 + swing, .02)))
    return hermite_motion(frames, channels)


def build(directory):
    directory.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='re4-synthetic-melee-') as temporary:
        source = Path(temporary)
        with redirect_stdout(io.StringIO()):
            grab.build(source)
        archives = {name: generated_entries((source / name).read_bytes())
                    for name in ('PL00.drs', 'WEP01.drs', 'EM12.drs')}
    player, weapon, enemy = (archives[name] for name in
                              ('PL00.drs', 'WEP01.drs', 'EM12.drs'))
    for entries in (player, weapon, enemy):
        for entry, (tag, data) in list(entries.items()):
            if tag == 'FCV':
                entries[entry] = ('FCV', upgrade_generated_motion(data))
            elif tag == 'BIN':
                joints = data[25]
                # Preserve the independent four-part weapon's M20 rest pose.
                if joints in (119, 34):
                    display = struct.unpack_from('>I', data, 28)[0]
                    entries[entry] = ('BIN', model(joints, data[display + 12]))
    player[9] = ('BIN', model(119, weight=10, blade=True))
    player[31] = ('FCV', motion(50, 31, hand=True))
    player[32] = ('SEQ', grab.sequence(50))
    # cMot3 idle m0/m1/m2 and slash m0/m1/m2 use raw125/127/129
    # and raw126/128/130 respectively; raw131 is the knife sheath curve.
    for entry in range(125, 132):
        pitch = {127: .5, 129: -.5, 128: .5, 130: -.5}.get(entry, 0.)
        player[entry] = ('FCV', motion(50, entry, hand=True, pitch=pitch,
                                     slash=entry in (126, 128, 130)))
    weapon[45] = ('FCV', motion(50, 45, hand=True))
    enemy[665] = ('FCV', motion(50, 665))  # Leon's paired front-head kick.
    for fcv, seq in [(36, 37), (40, 41), (42, 43), (44, 45), (55, 56),
                     (59, 60), (61, 62), (63, 64), (65, 66), (71, 72),
                     (73, 74), (107, 108)]:
        frames = 70 if fcv == 107 else 50
        enemy[fcv] = ('FCV', motion(frames, fcv))
        enemy[seq] = ('SEQ', grab.sequence(frames))
    # DownSmall and DownDie choose individual face-up/face-down curves;
    # adjacent entry numbers here are both FCV, not FCV/SEQ pairs.
    for entry in (75, 76, 103, 104):
        enemy[entry] = ('FCV', motion(50, entry))
    manifest = {
        'synthetic': True,
        'original_asset_validation': False,
        'purpose': 'Generated M21 melee/parser/parent-transform/GPU fixtures',
        'base': 'make_grab_fixtures.py, generated in a temporary directory',
        'generated_skeleton': {
            'joints': {'PL00': 119, 'EM12': 34, 'WEP01_model': 4},
            'waist_chain': [0, 1, 2, 3],
            'forearm9_parent': 2, 'hand10_parent': 9,
            'knife_model_entry': 9, 'knife_vertex_weight_joint': 10,
            'knife_hit_source_part': 9,
            'original_rest_pose_validation': False,
        },
        'motion_policy': 'Zero root except inherited arbitrary EM12 walk raw4; '
                         'invented torso/hand curves and durations; all '
                         'channels use format0 Hermite with explicit tangents',
        'synthetic_walk': {'motion_entry': 4, 'units_per_tick': 100,
                           'original_speed_validation': False},
        'melee_entries': {
            'PL00': {'draw_fcv': 31, 'draw_seq': 32,
                     'ready_fcv': [125, 127, 129],
                     'slash_fcv': [126, 128, 130], 'sheath_fcv': 131},
            'WEP01': {'knife_to_gun_fcv': 45},
            'EM12': {'player_kick_fcv': 665,
                     'down_hit_fcv': [75, 76], 'down_death_fcv': [103, 104],
                     'reaction_pairs': [[36, 37], [40, 41], [42, 43], [44, 45],
                                        [55, 56], [59, 60], [61, 62], [63, 64],
                                        [65, 66], [71, 72], [73, 74],
                                        [107, 108]]},
        },
        'files': {},
    }
    for name, count in [('PL00.drs', 132), ('WEP01.drs', 54),
                        ('EM12.drs', 672)]:
        entries = archives[name]
        data = bytearray(grab.archive(count, entries))
        data[:32] = b'SYNTHETIC M21 TEST DATA ONLY!!'.ljust(32, b'\0')
        (directory / name).write_bytes(data)
        manifest['files'][name] = {
            'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest(),
            'entries': {str(entry): tag for entry, (tag, _) in
                        sorted(entries.items())}}
        print(f'SYNTHETIC {directory / name}: {len(data)} bytes')
    (directory / 'manifest.json').write_text(
        json.dumps(manifest, indent=2) + '\n', encoding='utf-8')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('output_directory', type=Path)
    build(parser.parse_args().output_directory)
