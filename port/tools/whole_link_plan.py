#!/usr/bin/env python3
"""Link plan for the whole-program port build (milestone 3).

Input: the compiled objects of main.dol and of every REL module. Output:

  stubs.cpp          logging stubs for every symbol nobody provides (Nintendo SDK,
                     CRI, SN toolchain leftovers). Compiled into libre4_main.
  modules.cpp        module id -> name table for the module loader.
  imports/<mod>.cpp  per module: names of the functions it calls in sibling
  imports/<mod>.S    modules, plus trampolines that resolve them on first call.
  link_report.json   what was generated and why.

"Nobody provides" is decided by a trial link of all objects against the C/C++
runtime of the target toolchain, so the platform C library is never stubbed.

Cross-module calls: stage modules (st1_*, st2_*, st3_*), the debug tools and
a few enemy/weapon modules call functions of sibling modules, and resolve each
other in a cycle (the GameCube loader patched imports whenever a sibling was
linked). ELF shared libraries cannot load such cycles eagerly (Android has no
lazy binding), so each such call goes through a small trampoline that looks
the target up in the loaded modules on first use.
"""
import argparse
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SYMBOLS_TXT = ROOT / "config" / "G4BE08" / "symbols.txt"
CALL_RELOCS = {"R_386_PLT32", "R_386_PC32", "R_X86_64_PLT32", "R_X86_64_PC32", "R_ARM_CALL", "R_ARM_JUMP24", "R_ARM_THM_CALL",
               "R_ARM_THM_JUMP24", "R_AARCH64_CALL26", "R_AARCH64_JUMP26"}


def nm_symbols(objects: list) -> tuple:
    """(defined globals -> type letter, undefined names) over a set of objects."""
    defined, undefined = {}, set()
    for chunk in range(0, len(objects), 200):
        out = subprocess.run(["nm", "-A", *objects[chunk:chunk + 200]],
                             capture_output=True, text=True, check=True).stdout
        for line in out.splitlines():
            # "<object>:<address> <type> <name>"; undefined entries have no address
            parts = line.split()
            if len(parts) != 3:
                continue
            if parts[1] == "U":
                undefined.add(parts[2])
            elif parts[1] in "TDBRVWGSCu":
                defined.setdefault(parts[2], parts[1])
    return defined, undefined - set(defined)


def call_targets(objects: list) -> set:
    """Symbols that are the target of at least one call relocation."""
    called = set()
    for chunk in range(0, len(objects), 200):
        out = subprocess.run(["readelf", "-rW", *objects[chunk:chunk + 200]],
                             capture_output=True, text=True).stdout
        for line in out.splitlines():
            parts = line.split()
            if len(parts) >= 5 and parts[2] in CALL_RELOCS:
                called.add(parts[4])
    return called


def trial_link(cxx: list, objects: list) -> list:
    """Symbols the toolchain's runtime libraries cannot provide either."""
    with tempfile.TemporaryDirectory() as tmp:
        rsp = Path(tmp) / "objects.rsp"
        rsp.write_text("\n".join(objects))
        cmd = [*cxx, "-fuse-ld=lld", "-shared", "-o", str(Path(tmp) / "trial.so"), f"@{rsp}",
               "-Wl,--no-undefined", "-Wl,--allow-multiple-definition", "-Wl,--no-demangle",
               "-Wl,--error-limit=0", "-lm"]
        out = subprocess.run(cmd, capture_output=True, text=True)
    missing = set(re.findall(r"undefined symbol: (\S+)", out.stderr))
    # defined by the generated files themselves (modules.cpp, stubs.cpp)
    missing -= {"kRe4Modules", "re4_stub_count"}
    if out.returncode != 0 and not missing:
        sys.exit(f"trial link failed for another reason:\n{out.stderr[-3000:]}")
    return sorted(missing)


def original_symbol_types() -> dict:
    """name -> (type, size) for the symbols of main.dol (config/G4BE08/symbols.txt)."""
    types = {}
    for line in SYMBOLS_TXT.read_text().splitlines():
        m = re.match(r"(\S+) = \S+; // type:(\w+)(?: size:(0x[0-9A-Fa-f]+))?", line)
        if m:
            types[m[1]] = (m[2], int(m[3], 16) if m[3] else 0)
    return types


def demangle(names: list) -> list:
    out = subprocess.run(["c++filt"], input="\n".join(names), capture_output=True, text=True).stdout
    return out.splitlines()


def c_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_if_changed(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def stubs_source(funcs: list, datas: list, sizes: dict) -> str:
    names = funcs + [d for d in datas]
    plain = demangle(names) if names else []
    lines = [
        "// Generated by port/tools/whole_link_plan.py: symbols no object and no",
        "// runtime library provides. Functions log their first call and return 0.",
        "#include \"re4_runtime.h\"",
        "",
        f"static const char* const kStubNames[{max(len(funcs), 1)}] = {{",
    ]
    lines += [f"    {c_string(p)}," for p in plain[:len(funcs)]] or ["    \"\","]
    lines += ["};", f"static unsigned char kStubSeen[{max(len(funcs), 1)}];", ""]
    for i, name in enumerate(funcs):
        lines.append(f"extern \"C\" long long re4_stub_{i}() __asm__({c_string(name)});")
        lines.append(f"extern \"C\" long long re4_stub_{i}() {{ re4_stub_hit(kStubNames, kStubSeen, {i}); return 0; }}")
    lines.append("")
    for i, name in enumerate(datas):
        size = max(sizes.get(name, 0), 64) if sizes.get(name) else 4096
        lines.append(f"// data: {plain[len(funcs) + i]}")
        lines.append(f"extern \"C\" __attribute__((aligned(16))) unsigned char re4_stub_data_{i}[{size}] "
                     f"__asm__({c_string(name)});")
        lines.append(f"unsigned char re4_stub_data_{i}[{size}];")
    lines += ["", f"extern \"C\" int re4_stub_count() {{ return {len(funcs)}; }}", ""]
    return "\n".join(lines)


def trampolines_asm(arch: str, names: list) -> str:
    out = ["// Generated by port/tools/whole_link_plan.py: cross-module call trampolines.",
           "// Each resolves its target in the loaded sibling modules on first call",
           "// (re4_module_import_resolve, imports/<mod>.cpp) and tail-calls it with the",
           "// caller's arguments untouched.",
           "    .text"]
    if arch == "armv7":
        out += ["    .syntax unified", "    .arm"]
    for k, name in enumerate(names):
        out += [f"    .globl {name}", f"    .hidden {name}", f"    .type {name}, %function",
                "    .p2align 4", f"{name}:"]
        if arch == "i686":
            out += [f"    pushl ${k}",
                    "    call re4_module_import_resolve",
                    "    addl $4, %esp",
                    "    jmp *%eax"]
        elif arch == "armv7":
            out += ["    push {r0-r3, r12, lr}",
                    "    vpush {d0-d7}",
                    f"    movw r0, #{k}",
                    "    bl re4_module_import_resolve",
                    "    str r0, [sp, #80]",   # 64 bytes of d0-d7, then r0-r3: saved r12
                    "    vpop {d0-d7}",
                    "    pop {r0-r3, r12, lr}",
                    "    bx r12"]
        elif arch == "x86_64":
            # SysV: integer arguments rdi rsi rdx rcx r8 r9, vector xmm0-7, al
            # (vector register count of a variadic call); 7 pushes bring the
            # stack back to 16-byte alignment for the call
            out += ["    pushq %rdi", "    pushq %rsi", "    pushq %rdx", "    pushq %rcx",
                    "    pushq %r8", "    pushq %r9", "    pushq %rax",
                    "    subq $128, %rsp"]
            out += [f"    movdqu %xmm{i}, {16 * i}(%rsp)" for i in range(8)]
            out += [f"    movl ${k}, %edi",
                    "    call re4_module_import_resolve@PLT",
                    "    movq %rax, %r11"]
            out += [f"    movdqu {16 * i}(%rsp), %xmm{i}" for i in range(8)]
            out += ["    addq $128, %rsp",
                    "    popq %rax", "    popq %r9", "    popq %r8", "    popq %rcx",
                    "    popq %rdx", "    popq %rsi", "    popq %rdi",
                    "    jmp *%r11"]
        elif arch == "arm64":
            # AAPCS64: arguments x0-x7, x8 (indirect result), q0-q7
            out += ["    stp x29, x30, [sp, #-224]!",
                    "    mov x29, sp",
                    "    stp x0, x1, [sp, #16]", "    stp x2, x3, [sp, #32]",
                    "    stp x4, x5, [sp, #48]", "    stp x6, x7, [sp, #64]",
                    "    str x8, [sp, #80]",
                    "    stp q0, q1, [sp, #96]", "    stp q2, q3, [sp, #128]",
                    "    stp q4, q5, [sp, #160]", "    stp q6, q7, [sp, #192]",
                    f"    mov w0, #{k}",
                    "    bl re4_module_import_resolve",
                    "    mov x16, x0",
                    "    ldp q0, q1, [sp, #96]", "    ldp q2, q3, [sp, #128]",
                    "    ldp q4, q5, [sp, #160]", "    ldp q6, q7, [sp, #192]",
                    "    ldr x8, [sp, #80]",
                    "    ldp x0, x1, [sp, #16]", "    ldp x2, x3, [sp, #32]",
                    "    ldp x4, x5, [sp, #48]", "    ldp x6, x7, [sp, #64]",
                    "    ldp x29, x30, [sp], #224",
                    "    br x16"]
        else:
            sys.exit(f"no trampoline template for {arch}")
        out.append(f"    .size {name}, .-{name}")
    out.append('    .section .note.GNU-stack,"",%progbits')
    return "\n".join(out) + "\n"


def imports_source(module: str, funcs: list, datas: list) -> str:
    lines = [
        "// Generated by port/tools/whole_link_plan.py: functions this module calls in",
        f"// sibling modules ({module}).",
        "#include \"re4_runtime.h\"",
        "",
        f"static const char* const kImportNames[{max(len(funcs), 1)}] = {{",
    ]
    lines += [f"    {c_string(n)}," for n in funcs] or ["    \"\","]
    lines += ["};", f"static void* gImportSlots[{max(len(funcs), 1)}];", "",
              "extern \"C\" __attribute__((visibility(\"hidden\"))) void* re4_module_import_resolve(int k)",
              "{",
              "    if (!gImportSlots[k]) {",
              f"        gImportSlots[k] = re4_resolve_import({c_string(module)}, kImportNames[k]);",
              "    }",
              "    return gImportSlots[k];",
              "}",
              "",
              "// Forgets resolved targets; the loader calls it when a sibling module is unloaded.",
              f"extern \"C\" void re4_module_reset_imports_{module}()",
              "{",
              f"    for (int k = 0; k < {max(len(funcs), 1)}; k++) {{",
              "        gImportSlots[k] = 0;",
              "    }",
              "}",
              "",
              "// Resolves every import now; used by re4_host --check-modules.",
              f"extern \"C\" int re4_module_check_imports_{module}()",
              "{",
              "    int missing = 0;",
              f"    for (int k = 0; k < {len(funcs)}; k++) {{",
              f"        if (!re4_try_resolve_import(kImportNames[k])) {{",
              f"            re4_log(\"module {module}: unresolved import %s\", kImportNames[k]);",
              "            missing++;",
              "        }",
              "    }",
              "    return missing;",
              "}",
              ""]
    for i, name in enumerate(datas):
        # A data object of a sibling module cannot be reached through a call
        # trampoline; the module gets a private zeroed copy (listed in the report).
        lines.append(f"extern \"C\" __attribute__((visibility(\"hidden\"), aligned(16))) unsigned char "
                     f"re4_import_data_{i}[4096] __asm__({c_string(name)});")
        lines.append(f"unsigned char re4_import_data_{i}[4096];")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--plan", type=Path, required=True, help="modules.json from whole_prepare.py")
    ap.add_argument("--objects", type=Path, required=True,
                    help="text file: lines '<target>=<obj1>;<obj2>;...' (main, runtime, <module>...); "
                         "a target may repeat")
    ap.add_argument("--arch", required=True, choices=["i686", "armv7", "x86_64", "arm64"])
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("cxx", nargs=argparse.REMAINDER, help="-- compiler and target flags for the trial link")
    if "--emit-imports" in sys.argv:
        # Self-test helper: whole_link_plan.py --emit-imports MODULE ARCH OUT SYMBOL...
        i = sys.argv.index("--emit-imports")
        module, arch, out, *symbols = sys.argv[i + 1:]
        write_if_changed(Path(out) / f"{module}.cpp", imports_source(module, symbols, []))
        write_if_changed(Path(out) / f"{module}.S", trampolines_asm(arch, symbols))
        return 0
    args = ap.parse_args()
    cxx = [a for a in args.cxx if a != "--"]

    plan = json.loads(args.plan.read_text())
    groups = {}
    for line in args.objects.read_text().splitlines():
        if "=" in line:
            name, objs = line.split("=", 1)
            groups.setdefault(name, []).extend(o for o in objs.split(";") if o)
    main_objs = groups["main"] + groups.get("runtime", [])
    modules = {m: groups[m] for m in plan["modules"]}

    main_def, _ = nm_symbols(main_objs)
    mod_info = {m: nm_symbols(objs) for m, objs in modules.items()}
    every_object = main_objs + [o for objs in modules.values() for o in objs]
    called = call_targets(every_object)
    missing = trial_link(cxx, every_object)

    # Symbols a module needs from a sibling module (not from main or the runtime).
    providers = {}
    for m, (defined, _u) in mod_info.items():
        for s in defined:
            providers.setdefault(s, m)
    missing_set = set(missing)
    report = {"stubs": {}, "imports": {}, "data_imports": {}}
    import_names = set()
    for m, (defined, undefined) in mod_info.items():
        imports = sorted(s for s in undefined if s not in main_def and s in providers and s not in missing_set)
        funcs = [s for s in imports if providers[s] and mod_info[providers[s]][0][s] in "TW"]
        datas = [s for s in imports if s not in funcs]
        import_names.update(imports)
        report["imports"][m] = {s: providers[s] for s in funcs}
        if datas:
            report["data_imports"][m] = {s: providers[s] for s in datas}
        write_if_changed(args.out / "imports" / f"{m}.cpp", imports_source(m, funcs, datas))
        write_if_changed(args.out / "imports" / f"{m}.S", trampolines_asm(args.arch, funcs))

    # A symbol only modules provide does not count as missing for main; the
    # trial link above saw it defined, so `missing` only holds true gaps.
    originals = original_symbol_types()
    funcs, datas, sizes = [], [], {}
    for s in missing:
        kind, size = originals.get(s, (None, 0))
        if kind == "object" or (kind is None and s not in called and not s.startswith("_Z")):
            datas.append(s)
            sizes[s] = size
        else:
            funcs.append(s)
    report["stubs"] = {"functions": funcs, "data": datas}
    write_if_changed(args.out / "stubs.cpp", stubs_source(funcs, datas, sizes))

    table = ["// Generated by port/tools/whole_link_plan.py: REL module ids (rel.json).",
             "#include \"re4_runtime.h\"", "",
             "const Re4ModuleEntry kRe4Modules[] = {"]
    table += [f"    {{{info['id']}, {c_string(name)}}}," for name, info in plan["modules"].items()]
    table += ["    {0, 0},", "};", ""]
    write_if_changed(args.out / "modules.cpp", "\n".join(table))
    write_if_changed(args.out / "link_report.json", json.dumps(report, indent=1) + "\n")

    n_imports = sum(len(v) for v in report["imports"].values())
    print(f"link plan: {len(funcs)} function stubs, {len(datas)} data stubs, "
          f"{n_imports} cross-module calls, {sum(len(v) for v in report['data_imports'].values())} "
          f"cross-module data imports (private copies)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
